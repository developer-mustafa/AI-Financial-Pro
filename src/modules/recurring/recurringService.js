/**
 * Recurring-rule domain service.
 *
 * A recurring rule is a *template*, never a posted transaction. When an
 * occurrence becomes due the user reviews it and explicitly posts it, which
 * creates a real transaction stamped with a deterministic `occurrenceKey`
 * (`` `${rule.id}:${dueDate}` ``). That key is what makes generation idempotent:
 * an occurrence can never be posted twice, even across reloads or sync.
 *
 * Posting an occurrence advances `rule.nextDueDate` by one interval and records
 * `lastGeneratedDate`. The rule is therefore the single source of truth for
 * "what is next", and no background job is required.
 */

import { store as defaultStore, RESOURCES } from '../../core/state.js';
import { ids } from '../../utils/ids.js';
import { todayISO, nowISO } from '../../utils/date.js';
import { validateRecurring } from '../../utils/validation.js';
import {
  pendingOccurrences, recurringMonthlyEquivalent, recurringDueDates, advanceDueDate
} from '../../utils/calculations.js';

export function createRecurringService({ store = defaultStore, transactions } = {}) {
  const all = () => store.list(RESOURCES.RECURRING);

  function validate(input) {
    return validateRecurring(input, {
      accounts: store.list(RESOURCES.ACCOUNTS),
      categories: store.list(RESOURCES.CATEGORIES),
      preferences: store.preferences
    });
  }

  /** Builds the transaction payload a rule would produce on `dueDate`. */
  function buildOccurrence(rule, dueDate) {
    return {
      type: rule.type,
      amountMinor: rule.amountMinor,
      currency: rule.currency,
      categoryId: rule.type === 'transfer' ? null : rule.categoryId,
      accountId: rule.accountId,
      toAccountId: rule.type === 'transfer' ? rule.toAccountId : null,
      date: dueDate,
      description: rule.name,
      paymentMethod: rule.paymentMethod,
      status: 'posted',
      tags: [],
      notes: rule.notes,
      recurringRuleId: rule.id,
      occurrenceKey: ids.occurrence(rule.id, dueDate)
    };
  }

  const service = {
    all,
    get: (id) => store.byId(RESOURCES.RECURRING, id),
    active: () => all().filter((rule) => rule.status === 'active'),
    paused: () => all().filter((rule) => rule.status === 'paused'),
    validate,

    add(input) {
      const result = validate(input);
      if (!result.ok) return { ok: false, errors: result.errors };
      const record = { ...result.value, id: result.value.id || ids.recurring(), createdAt: nowISO(), updatedAt: nowISO() };
      store.apply('recurring:add', (draft) => {
        draft.recurringRules = [...draft.recurringRules, record];
        return [{ resource: RESOURCES.RECURRING, op: 'upsert', record }];
      });
      return { ok: true, record };
    },

    update(id, input) {
      const existing = store.byId(RESOURCES.RECURRING, id);
      if (!existing) return { ok: false, errors: { id: 'That recurring rule no longer exists.' } };
      const result = validate({ ...existing, ...input, id });
      if (!result.ok) return { ok: false, errors: result.errors };
      const record = { ...result.value, id, createdAt: existing.createdAt, updatedAt: nowISO() };
      store.apply('recurring:update', (draft) => {
        draft.recurringRules = draft.recurringRules.map((rule) => (rule.id === id ? record : rule));
        return [{ resource: RESOURCES.RECURRING, op: 'upsert', record }];
      });
      return { ok: true, record };
    },

    pause(id) {
      const existing = store.byId(RESOURCES.RECURRING, id);
      if (!existing) return { ok: false, errors: { id: 'That recurring rule no longer exists.' } };
      return service.update(id, { ...existing, status: 'paused' });
    },

    resume(id) {
      const existing = store.byId(RESOURCES.RECURRING, id);
      if (!existing) return { ok: false, errors: { id: 'That recurring rule no longer exists.' } };
      return service.update(id, { ...existing, status: 'active' });
    },

    /** Removes the rule but keeps every transaction it already generated. */
    remove(id) {
      const existing = store.byId(RESOURCES.RECURRING, id);
      if (!existing) return { ok: false, errors: { id: 'That recurring rule no longer exists.' } };
      store.apply('recurring:delete', (draft) => {
        draft.recurringRules = draft.recurringRules.filter((rule) => rule.id !== id);
        return [{ resource: RESOURCES.RECURRING, op: 'delete', id }];
      });
      return { ok: true, record: existing };
    },

    /** Count of transactions generated by a rule (used before deleting). */
    generatedCount(id) {
      return store.list(RESOURCES.TRANSACTIONS).filter((tx) => tx.recurringRuleId === id).length;
    },

    monthlyEquivalent: (rule) => recurringMonthlyEquivalent(rule),

    /** Occurrences that are due today or earlier and not yet posted. */
    due({ today = todayISO() } = {}) {
      return pendingOccurrences(all(), store.list(RESOURCES.TRANSACTIONS), { today });
    },
    dueCount() {
      return service.due().length;
    },

    /** Every occurrence of one rule from now up to `untilISO`. */
    schedule(id, { untilISO = todayISO() } = {}) {
      const rule = store.byId(RESOURCES.RECURRING, id);
      return rule ? recurringDueDates(rule, { untilISO }) : [];
    },

    /** The single next date a rule will fire, or null when exhausted. */
    nextDue(id) {
      const rule = store.byId(RESOURCES.RECURRING, id);
      if (!rule || rule.status !== 'active') return null;
      const dates = recurringDueDates(rule, { untilISO: '9999-12-31', maxOccurrences: 1 });
      return dates[0] || null;
    },

    /**
     * Posts one occurrence as a real transaction and advances the rule.
     * Idempotent: a second call for the same rule + due date is refused.
     * @returns {{ok:boolean, record?:object, errors?:object, duplicate?:boolean}}
     */
    post({ rule, dueDate }, { date = null } = {}) {
      if (!transactions) return { ok: false, errors: { service: 'The transaction service is unavailable.' } };
      const existing = store.byId(RESOURCES.RECURRING, rule.id);
      if (!existing) return { ok: false, errors: { id: 'That recurring rule no longer exists.' } };
      const key = ids.occurrence(rule.id, dueDate);
      if (store.list(RESOURCES.TRANSACTIONS).some((tx) => tx.occurrenceKey === key)) {
        return { ok: false, duplicate: true, errors: { occurrence: 'This occurrence has already been posted.' } };
      }

      const candidate = buildOccurrence({ ...existing, ...rule }, dueDate);
      if (date) candidate.date = date;
      const validated = transactions.validate(candidate);
      if (!validated.ok) return { ok: false, errors: validated.errors };

      const record = { ...validated.value, id: ids.transaction(), createdAt: nowISO(), updatedAt: nowISO() };
      const nextDueDate = advanceDueDate(dueDate, existing.frequency, existing.intervalCount);
      const updatedRule = { ...existing, nextDueDate, lastGeneratedDate: dueDate, updatedAt: nowISO() };

      store.apply('recurring:post', (draft) => {
        draft.transactions = [...draft.transactions, record];
        draft.recurringRules = draft.recurringRules.map((r) => (r.id === existing.id ? updatedRule : r));
        return [
          { resource: RESOURCES.TRANSACTIONS, op: 'upsert', record },
          { resource: RESOURCES.RECURRING, op: 'upsert', record: updatedRule }
        ];
      });
      return { ok: true, record };
    },

    /** Posts every currently-due occurrence, oldest first. */
    postAll({ today = todayISO() } = {}) {
      const results = { posted: 0, skipped: 0, failed: 0, records: [] };
      for (const item of service.due({ today })) {
        const result = service.post(item);
        if (result.ok) {
          results.posted += 1;
          results.records.push(result.record);
        } else if (result.duplicate) {
          results.skipped += 1;
        } else {
          results.failed += 1;
        }
      }
      return results;
    },

    /**
     * Skips one occurrence without creating a transaction by advancing the
     * rule past that due date. Used for "I did not spend this time".
     */
    skip({ rule, dueDate }) {
      const existing = store.byId(RESOURCES.RECURRING, rule.id);
      if (!existing) return { ok: false, errors: { id: 'That recurring rule no longer exists.' } };
      const nextDueDate = advanceDueDate(dueDate, existing.frequency, existing.intervalCount);
      const updatedRule = { ...existing, nextDueDate, lastGeneratedDate: dueDate, updatedAt: nowISO() };
      store.apply('recurring:skip', (draft) => {
        draft.recurringRules = draft.recurringRules.map((r) => (r.id === existing.id ? updatedRule : r));
        return [{ resource: RESOURCES.RECURRING, op: 'upsert', record: updatedRule }];
      });
      return { ok: true, record: updatedRule };
    },

    /** Rules whose next due date falls inside the next `days` days. */
    upcoming({ days = 30, today = todayISO() } = {}) {
      const limit = advanceDueDate(today, 'daily', days);
      const out = [];
      for (const rule of service.active()) {
        for (const dueDate of recurringDueDates(rule, { untilISO: limit, maxOccurrences: 24 })) {
          out.push({ rule, dueDate, key: ids.occurrence(rule.id, dueDate) });
        }
      }
      return out.sort((a, b) => (a.dueDate < b.dueDate ? -1 : a.dueDate > b.dueDate ? 1 : 0));
    },

    /** Monthly-equivalent total per currency (never mixed). */
    monthlyTotals() {
      const totals = new Map();
      for (const rule of service.active()) {
        const code = String(rule.currency || 'BDT').toUpperCase();
        totals.set(code, (totals.get(code) || 0) + recurringMonthlyEquivalent(rule));
      }
      return totals;
    },

    accountOptions() {
      return store.list(RESOURCES.ACCOUNTS).map((account) => ({
        value: account.id,
        label: `${account.name} · ${account.currency}${account.archived ? ' (archived)' : ''}`
      }));
    },

    categoryOptions(type) {
      const wanted = type === 'income' ? 'income' : 'expense';
      return store.orderedCategories(wanted).map((category) => ({
        value: category.id,
        label: `${'— '.repeat(category.depth)}${category.name}${category.archived ? ' (archived)' : ''}`
      }));
    }
  };

  return service;
}
